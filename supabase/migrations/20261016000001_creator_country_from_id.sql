create or replace function public.lock_country_to_id()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is not null and not public.is_admin() then
    -- The person themselves can never set or clear it.
    new.id_country := old.id_country;
  elsif new.is_verified and not old.is_verified and new.id_country is null then
    -- Just verified: the country of the document they verified with.
    select public.country_code(iv.country) into new.id_country
    from public.identity_verifications iv
    where iv.user_id = new.id
    limit 1;
  elsif old.is_verified and not new.is_verified then
    -- An admin removed "Verificado": the country is free again.
    new.id_country := null;
  end if;

  if new.id_country is not null then
    new.country := new.id_country;
  end if;
  return new;
end;
$$;

revoke execute on function public.lock_country_to_id() from public, anon, authenticated;

drop trigger if exists lock_country_to_id on public.profiles;
create trigger lock_country_to_id
  before update on public.profiles
  for each row execute function public.lock_country_to_id();

-- Creators verified before today.
update public.profiles p
   set id_country = public.country_code(iv.country)
  from public.identity_verifications iv
 where iv.user_id = p.id
   and p.is_verified
   and p.id_country is null
   and public.country_code(iv.country) is not null;
