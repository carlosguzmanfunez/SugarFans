-- A verified creator's country is the one on their identity document.
--
-- Until now the country was whatever the person picked at sign-up and could be
-- changed in Ajustes at any time, so "Top del mes por país" and the Explore
-- country filter could be gamed. From now on, when a creator is verified (Didit,
-- or an admin approving the manual form) the country that issued their document
-- is saved in profiles.id_country and their country follows it: Ajustes shows it
-- locked. Only the server and admins can change id_country; an admin who removes
-- "Verificado" also unlocks the country. Creators verified before this migration
-- get their document's country now.
--
-- Didit reports the issuing country as an English name ("Honduras") and an
-- alpha-3 code ("HND"); the manual form stores a name. public.country_code()
-- turns either (or a name in es/en/pt/fr/it) into the alpha-2 code the site uses.
--
-- Additive and safe to re-run.

-- ---------------------------------------------------------------------
-- Names and codes → ISO alpha-2
-- ---------------------------------------------------------------------
