create or replace function public.country_code(p text)
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select case
    when p is null or btrim(p) = '' then null
    when upper(btrim(p)) ~ '^[A-Z]{2}$'
      and exists (select 1 from public.country_aliases a where a.code = upper(btrim(p))) then upper(btrim(p))
    else (
      select a.code from public.country_aliases a
      where a.alias = lower(translate(btrim(p), 'ÁÉÍÓÚÜÑÇÂÊÎÔÛÃÕÀÈÌÒÙËÏáéíóúüñçâêîôûãõàèìòùëïÿ', 'AEIOUUNCAEIOUAOAEIOUEIaeiouuncaeiouaoaeioueiy'))
    )
  end
$$;

revoke execute on function public.country_code(text) from public, anon, authenticated;
grant execute on function public.country_code(text) to service_role;

