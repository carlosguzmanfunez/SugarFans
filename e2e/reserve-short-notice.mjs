import assert from 'node:assert/strict';
import {build} from 'esbuild';
import {fileURLToPath} from 'node:url';
const moduleOf=async file=>{const r=await build({entryPoints:[fileURLToPath(new URL(file,import.meta.url))],bundle:true,write:false,platform:'node',format:'esm',logLevel:'silent'});return import('data:text/javascript;base64,'+Buffer.from(r.outputFiles[0].text).toString('base64'));};
const vip=await moduleOf('../src/lib/vip.ts'),search=await moduleOf('../src/lib/creatorSearch.ts');
const now=new Date('2026-11-04T16:00:00Z'),date='2026-11-04';
const a={days:[0,1,2,3,4,5,6],hours:['09:30','10:00','10:30','11:00','11:30','12:00','12:30','13:00'],timeZone:'America/Tegucigalpa'};
assert.deepEqual(vip.freeHoursOn(a,[],date,1,30,{sameDay:true,now}),['11:00','11:30','12:00','12:30','13:00']);
console.log('OK Cinco espacios de media hora desde una hora después, en el mismo día');
assert.deepEqual(vip.freeHoursOn(a,[],date,24,30,{sameDay:true,now}),[]);
assert.deepEqual(vip.freeHoursOn(a,[],date,0,30,{sameDay:true,now}),['10:30','11:00','11:30','12:00','12:30','13:00']);
console.log('OK La anticipación de 24 horas se conserva; con cero nunca aparecen horas pasadas');
assert.deepEqual(vip.freeHoursOn(a,[{date,time:'11:00',timeZone:a.timeZone,durationMinutes:60}],date,1,30,{sameDay:true,now}),['12:00','12:30','13:00']);
console.log('OK Las ocupaciones bloquean todos los intervalos superpuestos');
assert.equal(vip.bookingWindow(now,a.timeZone).min,'2026-11-05');
assert.equal(vip.bookingWindow(now,a.timeZone,true).min,date);
assert.equal(vip.bookingWindow(new Date('2026-11-04T02:00:00Z'),a.timeZone,true).min,'2026-11-03');
assert.equal(vip.experienceAvailability(a,{details:{hours:['11:30','12:00']}}).hours.join(','),'11:30,12:00');
console.log('OK Las otras ventanas conservan su comportamiento y el día corresponde al creador');
const creator={name:'Diego Tórres',username:'diego_torres'};
for(const q of ['Diego Torres','diego_torres','@diego_torres',' @DiEgO_ '])assert.equal(search.matchesCreatorSearch(creator,q),true,q);
assert.equal(search.matchesCreatorSearch(creator,'@otro'),false);
assert.equal(search.matchesCreatorSearch({name:'Diego Tórres',username:'otro'},'@diego'),false);
console.log('OK Búsqueda por nombre o @usuario, parcial, sin distinguir mayúsculas ni acentos');
